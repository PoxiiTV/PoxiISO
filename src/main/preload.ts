import { contextBridge, ipcRenderer, webUtils } from 'electron'

contextBridge.exposeInMainWorld('poxi', {
  listUsb: () => ipcRenderer.invoke('usb:list'),
  install: (o: unknown) => ipcRenderer.invoke('install', o),
  onProgress: (cb: (p: number) => void) => ipcRenderer.on('progress', (_e, p) => cb(p)),
  dict: () => ipcRenderer.invoke('dict'),
  listIsos: (l: string) => ipcRenderer.invoke('isos:list', l),
  pickIsos: () => ipcRenderer.invoke('isos:pick'),
  copyIsos: (l: string, paths: string[]) => ipcRenderer.invoke('isos:copy', l, paths),
  cancelCopy: () => ipcRenderer.send('isos:cancel'),
  deleteIso: (l: string, rel: string) => ipcRenderer.invoke('isos:delete', l, rel),
  onIsoProgress: (cb: (p: unknown) => void) => ipcRenderer.on('isos:progress', (_e, p) => cb(p)),
  pathsFromFiles: (files: File[]) => files.map(f => webUtils.getPathForFile(f)),
  dlCatalog: () => ipcRenderer.invoke('dl:catalog'),
  dlStart: (arg: unknown) => ipcRenderer.invoke('dl:start', arg),
  dlCancel: () => ipcRenderer.send('dl:cancel'),
  dlOpenPage: (id: string) => ipcRenderer.invoke('dl:openPage', id),
  dlOpenFolder: () => ipcRenderer.send('dl:openFolder'),
  dlCleanup: (p: string) => ipcRenderer.invoke('dl:cleanup', p),
  onDlProgress: (cb: (p: unknown) => void) => ipcRenderer.on('dl:progress', (_e, p) => cb(p)),
  appInfo: () => ipcRenderer.invoke('app:info'),
  dlClearParts: () => ipcRenderer.invoke('dl:clearParts'),
  openLink: (k: string) => ipcRenderer.send('open-link', k),
  plugsonStart: (letter: string, lang: string) => ipcRenderer.invoke('plugson:start', letter, lang),
  plugsonStatus: () => ipcRenderer.invoke('plugson:status'),
  bootPreview: (letter: string | null) => ipcRenderer.invoke('boot:preview', letter),
  plugsonStop: () => ipcRenderer.send('plugson:stop'),
  plugsonReopen: () => ipcRenderer.send('plugson:reopen'),
  onPlugsonClosed: (cb: () => void) => ipcRenderer.on('plugson:closed', () => cb()),
  win: (a: 'min' | 'max' | 'close') => ipcRenderer.send('win', a),
})
